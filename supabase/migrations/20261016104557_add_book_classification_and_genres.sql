-- 1. Add classification to books table
ALTER TABLE public.books 
ADD COLUMN IF NOT EXISTS classification TEXT;

-- 2. Restict classification column
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 
    FROM pg_constraint 
    WHERE conname = 'books_classification_check'
      AND conrelid = 'public.books'::regclass
  ) THEN
    ALTER TABLE public.books 
    ADD CONSTRAINT books_classification_check
        CHECK (
            classification IS NULL
            OR classification IN ('classic', 'contemporary')
        );
    END IF;
    END $$;

    -- 3. Create genres table
    CREATE TABLE IF NOT EXISTS public.genres (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL UNIQUE,
        slug TEXT NOT NULL UNIQUE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    -- 4. Create book_genres JUNCTION table 
    CREATE TABLE IF NOT EXISTS public.book_genres (
        book_id BIGINT NOT NULL REFERENCES public.books(id) ON DELETE CASCADE,
        genre_id BIGINT NOT NULL REFERENCES public.genres(id) ON DELETE CASCADE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        PRIMARY KEY (book_id, genre_id)
    );

    -- 5. REMOVE genre column if EXISTS from books
    ALTER TABLE public.books
    DROP COLUMN IF EXISTS genre;
