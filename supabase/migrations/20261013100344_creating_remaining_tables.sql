-- 1. Added ENUMES TYES
CREATE TYPE public.profile_role AS ENUM (
    'user', 
    'admmin',
    'moderator'
);


CREATE TYPE public.order_status AS ENUM (
   'pending',
   'processing',
   'delivered',
   'shipped',
   'completed',
    'cancelled'
);


CREATE TYPE public.payments_status AS ENUM (
     'pending',
     'paid',
     'failed',
     'refunded'
);


-- 2. PROFILES
CREATE TABLE public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    full_name TEXT,
    avatar_url TEXT,
    role public.profile_role NOT NULL DEFAULT 'user',
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- 3. CATEGORIES 
CREATE TABLE public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNiQUE,
    slug TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- 4. AUTHORS 
CREATE TABLE public.authors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    bio TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- 5. CART ITEMS 
CREATE TABLE public.cart_items (
    id SERIAL PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    book_id BIGINT NOT NULL REFERENCES public.books(id) ON DELETE CASCADE,
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(user_id, book_id)
);


-- 6. ORDERS 


CREATE TABLE public.orders (
    id SERIAL PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    total_amount NUMERIC(10,2) NOT NULL CHECK (total_amount >= 0),
    status public.order_status NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- 7. ORDERS ITEMS 
CREATE TABLE public.order_items (
    id SERIAL PRIMARY KEY,
    order_id INT NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    book_id BIGINT REFERENCES public.books(id) ON DELETE SET NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0)
);


-- 8. PAYMENTS 
CREATE TABLE public.payments (
    id SERIAL PRIMARY KEY,
    order_id INT NOT NULL REFERENCES public.orders(id),
    stripe_payment_id TEXT UNIQUE,
    amount NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
    status public.payments_status NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- 9. REVIEWS
CREATE TABLE public.reviews (
    id SERIAL PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    book_id BIGINT NOT NULL REFERENCES public.books(id) ON DELETE CASCADE,
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     UNIQUE (user_id, book_id)
);


-- 10. WISHLIST
create table public.wishlist (
    id serial primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    book_id bigint not null references public.books(id) on delete cascade,
    created_at timestamptz not null default now(),
    unique (user_id, book_id)
);


-- 11. ADD FK BOOKS to categories and authors


ALTER TABLE public.books ADD CONSTRAINT book_id_author_fk FOREIGN KEY(author_id) REFERENCES public.authors(id);


ALTER TABLE public.books ADD CONSTRAINT book_id_category_fk FOREIGN KEY(category_id) REFERENCES public.categories(id);